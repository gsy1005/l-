def translate_chart(cd: dict) -> dict:
    """翻译图表定义中的标题、轨迹名、参考线标签"""
    if cd.get("title"):
        cd["title"] = translate_text(str(cd["title"]))
    for r in cd.get("refs") or []:
        if isinstance(r, dict) and r.get("label"):
            lbl = str(r["label"])
            r["label"] = CHART_ZH.get(lbl, translate_text(lbl))
    if isinstance(cd.get("band"), dict) and cd["band"].get("label"):
        cd["band"]["label"] = translate_text(str(cd["band"]["label"]))
    for tr in cd.get("traces") or []:
        if isinstance(tr, dict) and tr.get("name"):
            nm = str(tr["name"])
            tr["name"] = CHART_ZH.get(nm, translate_text(nm))
    return cd


_EXTRA_CODES = ("BAMLC0A4CBBB|BAMLEMCBPIOAS|BAMLH0A2HYB|DCPF3M|DFII10|DGS5|DTB3|OBFRVOL|STLFSI4|"
                "T10YIE|TGCRVOLUME|WSEFINTL1|WSHOBL|WSHOMCB|WSHONBNL|WSHOSHO|SOFR1|SOFR25|SOFR75|"
                "EFFR01|BAMLEM|SPY5")
EXTRA_CODE_RE = re.compile(r"\b(?:" + _EXTRA_CODES + r")\b")


def translate_text(t: str) -> str:
    if not t or not re.search(r"[A-Za-z]", t):
        return t
    t = EXTRA_CODE_RE.sub("", t)
    if t.strip() in EXACT:
        return EXACT[t.strip()]
    # 1) 句子级 (键为清洗后英文原文)
    for en, zh in PHRASES:
        if en in t:
            t = t.replace(en, zh)
    # 2) 片段模式
    for rx, rep in PATTERNS:
        t = rx.sub(rep, t)
    # "moved from watch to normal (now 194 bp)." 类动态句
    def _mv(m):
        zh = {"watch": "关注", "normal": "正常", "elevated": "偏高", "stress": "压力",
              "extreme": "极端", "quiet": "平静"}.get(m.group(1).lower(), m.group(1))
        zh2 = {"watch": "关注", "normal": "正常", "elevated": "偏高", "stress": "压力",
               "extreme": "极端"}.get(m.group(2).lower(), m.group(2))
        return f"从「{zh}」转为「{zh2}」(现值 {m.group(3)})"
    t = re.sub(r"moved from (\w+) to (\w+) \(now ([^)]+)\)", _mv, t)
    return re.sub(r" {2,}", " ", t).strip()
